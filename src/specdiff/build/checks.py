from __future__ import annotations

import subprocess
from pathlib import Path

from specdiff.build.files import resolve_output_path

# Enough of a failing command's output to diagnose it without flooding the prompt.
MAX_OUTPUT_CHARS = 12000


def static_problems(
    files: dict[str, str], output_dir: str, others: dict[str, str], ours: set[str]
) -> list[str]:
    """Problems found without running anything: bad paths, ownership, Python syntax.

    ours holds the paths this node already owns; any other existing file was not
    generated by specdiff and must not be overwritten.
    """
    problems: list[str] = []
    for path, contents in files.items():
        try:
            full = resolve_output_path(output_dir, path)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        if path in others:
            problems.append(
                f"{path} belongs to spec `{others[path]}`. Import from it instead of writing it."
            )
        elif path not in ours and full.exists():
            problems.append(
                f"{path} already exists and was not generated by specdiff. Use another path."
            )
        if path.endswith(".py"):
            try:
                compile(contents, path, "exec")
            except SyntaxError as exc:
                problems.append(f"{path}:{exc.lineno}: SyntaxError: {exc.msg}")
    return problems


def run_command(command: str, cwd: Path | None = None) -> tuple[bool, str]:
    """Run a shell command from the project root. Returns (passed, combined output)."""
    result = subprocess.run(command, shell=True, capture_output=True, text=True, cwd=cwd)
    output = result.stdout + result.stderr
    # pytest exits 5 when it collects nothing, e.g. before any spec with tests is built.
    passed = result.returncode == 0 or (result.returncode == 5 and "no tests ran" in output)
    if len(output) > MAX_OUTPUT_CHARS:
        output = "[...output truncated...]\n" + output[-MAX_OUTPUT_CHARS:]
    return passed, output
